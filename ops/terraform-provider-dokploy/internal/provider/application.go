// dokploy_application: a Dokploy Application (one Swarm service built from a
// Git repository or pulled from a Docker image).
//
// How the API is used (see apps/dokploy/server/api/routers/application.ts):
//
//   - application.create only takes name, appName, description, environmentId
//     and serverId (zod strips every other key); the new row gets the default
//     build server of the organization. Everything else is written right after
//     through application.update, in the same Terraform apply.
//   - application.update accepts every column except serverId, buildServerId
//     and buildRegistryId, and ignores appName. It is also used for the source
//     (github/gitlab/...), the build type and the Docker image: the dedicated
//     save*Provider / saveBuildType procedures only add input validation and
//     reset applicationStatus to "idle", which Terraform has no business doing.
//   - the build server and its registry move together through
//     application.updateBuildServer (both ids are required);
//   - the environment is moved with application.move;
//   - the server cannot change: server_id forces a new resource, and app_name is generated
//     (prefix plus a random suffix), so it is read-only with a write-only app_name_prefix;
//   - env goes through application.saveEnvironment, which wants env,
//     buildArgs, buildSecrets and createEnvFile at once: the current values of
//     the three others are read back and passed through, so they are not wiped;
//   - Terraform never calls deploy, redeploy, start, stop or reload. A change
//     of the configuration is applied to the running service by the next
//     deployment, which stays a manual or webhook-driven decision.
//
// Never mapped: refreshToken (webhook secret, read-only noise), the secrets of
// the Docker source (write-only, see docker_username_wo / docker_password_wo).

func init() {
	app := &Spec{
		Name: "application",
		Desc: "A Dokploy application: a Docker Swarm service built from a Git repository or pulled from a Docker image. " +
			"Terraform only manages its configuration and never triggers a deployment: a change is applied to the running service by the next deployment. " +
			"Dokploy gives a new application the default build server; set build_server_id and build_registry_id to change it. " +
			"Domains, mounts, ports, redirects and security (basic auth) are separate resources. " +
			"Environment variables follow the public/secret split of every service (env, secret_env_keys, secret_env_wo).",
		IDKey:          "applicationId",
		ImportHint:     "Import with the applicationId.",
		SecretsVersion: true,
		Fields:         applicationFields(),
		Env:            &EnvSpec{Save: applicationSaveEnv},
	}
	app.UseREST(CRUD{Router: "application", DeleteProc: "application.delete"})
	app.Create = applicationCreate
	app.Update = applicationUpdate
	register(app)
}

