// applicationEnvTextToMap turns a dotenv text into a map of the literal values.
func applicationEnvTextToMap(v any) any {
	s, _ := v.(string)
	out := map[string]any{}
	for _, e := range parseEnv(s) {
		out[e.Key] = e.Value
	}
	return out
}

// applicationMapToEnvText renders a map of strings as a dotenv text sorted by
// key; the empty map renders as the empty text.
func applicationMapToEnvText(v any) any {
	m, _ := v.(map[string]any)
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	for _, k := range keys {
		b.WriteString(k + "=" + asString(m[k]) + "\n")
	}
	return b.String()
}

// applicationNoUpdateKeys are the payload keys that application.update does
// not take: they have their own procedure, or cannot change at all.
var applicationNoUpdateKeys = map[string]bool{
	"applicationId":   true,
	"environmentId":   true, // application.move
	"serverId":        true, // ForceNew
	"appName":         true, // ForceNew
	"buildServerId":   true, // application.updateBuildServer
	"buildRegistryId": true, // application.updateBuildServer
}

// applicationEnvTexts are the payload keys that hold a dotenv text; they are
// compared by content, not by formatting (comments, order, blank lines).
var applicationEnvTexts = map[string]bool{
	"buildArgs": true, "buildSecrets": true,
	"previewBuildArgs": true, "previewBuildSecrets": true, "previewEnv": true,
}

// applicationSameJSON compares two decoded JSON values, treating a missing
// list and an empty one alike.
func applicationSameJSON(a, b any) bool {
	norm := func(v any) any {
		if l, ok := v.([]any); ok && len(l) == 0 {
			return nil
		}
		return v
	}
	x, err1 := json.Marshal(norm(a))
	y, err2 := json.Marshal(norm(b))
	return err1 == nil && err2 == nil && string(x) == string(y)
}

func applicationRead(ctx context.Context, c *client.Client, id string) (map[string]any, error) {
	var out map[string]any
	if err := c.Query(ctx, "application.one", map[string]any{"applicationId": id}, &out); err != nil {
		return nil, err
	}
	if out == nil {
		return nil, client.ErrNotFound
	}
	return out, nil
}

func applicationCreate(ctx context.Context, c *client.Client, in Input) (string, error) {
	// Fail before creating anything: the build server and its registry move
	// together, and a new application has no registry yet.
	if _, ok := in.Body["buildServerId"]; ok {
		if _, ok := in.Body["buildRegistryId"]; !ok {
			return "", errors.New("build_server_id needs build_registry_id: Dokploy sets the build server and its registry together")
		}
	}
	var created map[string]any
	if err := c.Mutate(ctx, "application.create", pick(in.Body, "name", "appName", "description", "environmentId", "serverId"), &created); err != nil {
		return "", err
	}
	id := asString(created["applicationId"])
	if id == "" {
		return "", errors.New("the API answer carries no applicationId")
	}
	remote, err := applicationRead(ctx, c, id)
	if err == nil {
		err = applicationSync(ctx, c, id, in.Body, remote)
	}
	if err != nil {
		// The engine keeps nothing when Create fails: do not leave a
		// half-configured application behind (it was never deployed).
		if derr := c.Mutate(ctx, "application.delete", map[string]any{"applicationId": id}, nil); derr != nil && !errors.Is(derr, client.ErrNotFound) {
			return "", fmt.Errorf("%w (the new application %s could not be removed either: delete it in Dokploy or import it)", err, id)
		}
		return "", fmt.Errorf("%w (the new application was removed again)", err)
	}
	return id, nil
}

func applicationUpdate(ctx context.Context, c *client.Client, in Input) error {
	return applicationSync(ctx, c, in.ID, in.Body, in.Remote)
}

// applicationSync writes what differs between the planned body and the remote
// object, through the procedure that owns each part. Comparing with the remote
// object keeps an apply from rewriting (or resetting) columns it does not
// change, and makes a retry after a half-failed apply safe.
func applicationSync(ctx context.Context, c *client.Client, id string, body, remote map[string]any) error {
	// Check the build server first, so that a refusal leaves nothing half-applied.
	curServer, curRegistry := asString(remote["buildServerId"]), asString(remote["buildRegistryId"])
	wantServer, wantRegistry := curServer, curRegistry
	if v := asString(body["buildServerId"]); v != "" {
		wantServer = v
	}
	if v := asString(body["buildRegistryId"]); v != "" {
		wantRegistry = v
	}
	buildServerChanges := wantServer != curServer || wantRegistry != curRegistry
	if buildServerChanges && (wantServer == "" || wantRegistry == "") {
		return errors.New("build_server_id and build_registry_id must both be set: Dokploy changes the build server and its registry together")
	}

	changed := map[string]any{}
	for k, v := range body {
		if applicationNoUpdateKeys[k] {
			continue
		}
		if applicationEnvTexts[k] {
			if !sameEnv(parseEnv(asString(v)), parseEnv(asString(remote[k]))) {
				changed[k] = v
			}
			continue
		}
		if !applicationSameJSON(v, remote[k]) {
			changed[k] = v
		}
	}
	if len(changed) > 0 {
		changed["applicationId"] = id
		if err := c.Mutate(ctx, "application.update", changed, nil); err != nil {
			return err
		}
	}
	if env := asString(body["environmentId"]); env != "" && env != asString(remote["environmentId"]) {
		if err := c.Mutate(ctx, "application.move", map[string]any{"applicationId": id, "targetEnvironmentId": env}, nil); err != nil {
			return err
		}
	}
	if buildServerChanges {
		return c.Mutate(ctx, "application.updateBuildServer", map[string]any{
			"applicationId": id, "buildServerId": wantServer, "buildRegistryId": wantRegistry,
		}, nil)
	}
	return nil
}

// applicationSaveEnv stores the environment text. application.saveEnvironment
// also carries the build arguments, the build secrets and createEnvFile and
// wants all of them: they are read back right now (the application may have
// just been changed in the same apply) and passed through unchanged.
func applicationSaveEnv(ctx context.Context, c *client.Client, id, text string, _ map[string]any) error {
	fresh, err := applicationRead(ctx, c, id)
	if err != nil {
		return err
	}
	createEnvFile, ok := fresh["createEnvFile"].(bool)
	if !ok {
		createEnvFile = true
	}
	return c.Mutate(ctx, "application.saveEnvironment", map[string]any{
		"applicationId": id,
		"env":           text,
		"buildArgs":     asString(fresh["buildArgs"]),
		"buildSecrets":  asString(fresh["buildSecrets"]),
		"createEnvFile": createEnvFile,
	}, nil)
}
