// composeBuildPair returns the build server and registry the plan asks for;
// values the plan does not know keep what remote holds (nil on create).
func composeBuildPair(plan Obj, remote map[string]any) (server, registry string, err error) {
	want := func(attr, api string) string {
		if v, ok := stringOf(plan[attr]); ok {
			return v
		}
		return asString(remote[api])
	}
	server, registry = want("build_server_id", "buildServerId"), want("build_registry_id", "buildRegistryId")
	if (server == "") != (registry == "") {
		return "", "", fmt.Errorf("build_server_id and build_registry_id must be set together (or both left empty)")
	}
	return server, registry, nil
}

// composeSetBuildServer calls compose.updateBuildServer; empty ids disable it.
func composeSetBuildServer(ctx context.Context, c *client.Client, id, server, registry string) error {
	body := map[string]any{"composeId": id, "buildServerId": nil, "buildRegistryId": nil}
	if server != "" {
		body["buildServerId"], body["buildRegistryId"] = server, registry
	}
	return c.TRPCMutate(ctx, "compose.updateBuildServer", body, nil)
}

// composeChanged keeps the entries of body whose value differs from what the
// API holds. Absent, null, "" and an empty list are the same thing to Dokploy.
func composeChanged(body, remote map[string]any) map[string]any {
	out := map[string]any{}
	for k, v := range body {
		if !composeSame(v, remote[k]) {
			out[k] = v
		}
	}
	return out
}

func composeSame(a, b any) bool {
	if composeEmpty(a) && composeEmpty(b) {
		return true
	}
	ja, errA := json.Marshal(a)
	jb, errB := json.Marshal(b)
	if errA != nil || errB != nil {
		return reflect.DeepEqual(a, b)
	}
	return string(ja) == string(jb)
}

func composeEmpty(v any) bool {
	switch x := v.(type) {
	case nil:
		return true
	case string:
		return x == ""
	case []any:
		return len(x) == 0
	}
	return false
}

// composeLooksRaw reports whether a create payload describes an inline compose
// file and no Git source.
func composeLooksRaw(body map[string]any) bool {
	if _, set := body["sourceType"]; set {
		return false
	}
	if file, _ := body["composeFile"].(string); file == "" {
		return false
	}
	for _, k := range composeGitKeys {
		if v, ok := body[k]; ok && !composeEmpty(v) {
			return false
		}
	}
	return true
}

func composeCreate(ctx context.Context, c *client.Client, in Input) (string, error) {
	server, registry, err := composeBuildPair(in.Plan, nil)
	if err != nil {
		return "", err
	}
	createBody := pick(in.Body, "name", "description", "environmentId", "composeType", "serverId", "composeFile", "appName")
	var created map[string]any
	if err := c.Mutate(ctx, "compose.create", createBody, &created); err != nil {
		return "", err
	}
	id := asString(created["composeId"])
	if id == "" {
		return "", fmt.Errorf("the API answer carries no composeId")
	}
	if err := composeConfigure(ctx, c, id, in, created, server, registry); err != nil {
		// The compose exists but is not configured as planned and the engine
		// cannot keep it in the state from here: remove it (nothing was
		// deployed, volumes are kept) rather than leave an orphan behind.
		if delErr := c.Mutate(ctx, "compose.delete", map[string]any{"composeId": id, "deleteVolumes": false}, nil); delErr != nil {
			return "", fmt.Errorf("%w (the half-created compose %s could not be removed: %v)", err, id, delErr)
		}
		return "", fmt.Errorf("%w (the half-created compose was removed)", err)
	}
	return id, nil
}

// composeConfigure applies what compose.create does not accept.
func composeConfigure(ctx context.Context, c *client.Client, id string, in Input, created map[string]any, server, registry string) error {
	rest := map[string]any{}
	for k, v := range in.Body {
		if !composeCreateKeys[k] && !composeNotUpdatable[k] {
			rest[k] = v
		}
	}
	if composeLooksRaw(in.Body) {
		rest["sourceType"] = "raw"
	}
	rest = composeChanged(rest, created)
	if len(rest) > 0 {
		rest["composeId"] = id
		if err := c.Mutate(ctx, "compose.update", rest, nil); err != nil {
			return fmt.Errorf("configure the new compose: %w", err)
		}
	}
	if server != "" {
		if err := composeSetBuildServer(ctx, c, id, server, registry); err != nil {
			return fmt.Errorf("set the build server of the new compose: %w", err)
		}
	}
	return nil
}

func composeUpdate(ctx context.Context, c *client.Client, in Input) error {
	server, registry, err := composeBuildPair(in.Plan, in.Remote)
	if err != nil {
		return err
	}
	buildChanged := server != asString(in.Remote["buildServerId"]) || registry != asString(in.Remote["buildRegistryId"])
	disabling := buildChanged && server == ""
	// Disabling first: the build server rules only apply when one is set, and
	// the other changes below may be incompatible with it.
	if disabling {
		if err := composeSetBuildServer(ctx, c, in.ID, "", ""); err != nil {
			return err
		}
	}
	if env, ok := stringOf(in.Plan["environment_id"]); ok && env != asString(in.Remote["environmentId"]) {
		move := map[string]any{"composeId": in.ID, "targetEnvironmentId": env}
		if err := c.Mutate(ctx, "compose.move", move, nil); err != nil {
			return err
		}
	}
	body := map[string]any{}
	for k, v := range in.Body {
		if k != "composeId" && !composeNotUpdatable[k] {
			body[k] = v
		}
	}
	if body = composeChanged(body, in.Remote); len(body) > 0 {
		body["composeId"] = in.ID
		if err := c.Mutate(ctx, "compose.update", body, nil); err != nil {
			return err
		}
	}
	if buildChanged && !disabling {
		return composeSetBuildServer(ctx, c, in.ID, server, registry)
	}
	return nil
}
