// dokploy_compose: a Compose service (docker-compose or Swarm stack).
//
// How the API really behaves (read from the router and the zod schemas):
//
//   - compose.create only accepts name, description, environmentId, composeType,
//     appName, serverId and composeFile. Everything else (source, git provider,
//     flags) goes through compose.update, which is a partial update.
//   - compose.update silently drops serverId, buildServerId, buildRegistryId and
//     appName: the runtime server and the app name are fixed at creation, the
//     build server has its own procedure, compose.updateBuildServer (tRPC only,
//     its input carries a refine() the REST facade cannot describe).
//   - appName given on create is only a prefix: Dokploy appends "-<6 random
//     chars>". It is therefore exposed as the write-only app_name_prefix, and the
//     real name as the read-only app_name.
//   - compose.saveEnvironment stores the environment text and answers `true`.
//   - compose.delete wants deleteVolumes; the provider always sends false.
//   - No procedure used here deploys anything.

// composeCreateKeys are the payload keys compose.create accepts.
var composeCreateKeys = map[string]bool{
	"name": true, "description": true, "environmentId": true, "composeType": true,
	"appName": true, "serverId": true, "composeFile": true,
}

// composeNotUpdatable are the payload keys compose.update does not take (or
// that other procedures own).
var composeNotUpdatable = map[string]bool{
	"appName": true, "serverId": true, "buildServerId": true, "buildRegistryId": true,
	"environmentId": true,
}

// composeGitKeys are the payload keys that say the source is a Git provider.
var composeGitKeys = []string{
	"repository", "owner", "branch", "githubId",
	"gitlabId", "gitlabRepository", "gitlabOwner", "gitlabBranch", "gitlabProjectId", "gitlabPathNamespace",
	"bitbucketId", "bitbucketRepository", "bitbucketRepositorySlug", "bitbucketOwner", "bitbucketBranch",
	"giteaId", "giteaRepository", "giteaOwner", "giteaBranch",
	"customGitUrl", "customGitBranch", "customGitSSHKeyId",
}

// composeNilToEmpty shows an absent value as an empty string, so that "" in a
// configuration means "none" (the only way to clear an Optional+Computed
// attribute) and stays stable across refreshes.
func composeNilToEmpty(v any) any {
	if v == nil {
		return ""
	}
	return v
}

// composeEmptyToNil sends "" as null: the id columns are foreign keys.
func composeEmptyToNil(v any) any {
	if v == "" {
		return nil
	}
	return v
}

// composeNullableText are the text attributes Dokploy stores as NULL when
